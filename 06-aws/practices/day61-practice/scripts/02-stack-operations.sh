#!/bin/bash
# ================================================
# 02-stack-operations.sh
# CloudFormation Stack Operations Reference
# Author: Asim Raza - Day 61
# ================================================
set -euo pipefail

REGION="${AWS_DEFAULT_REGION:-us-east-1}"
APP_NAME="devops-journey"
ENVIRONMENT="staging"
STACK_NAME="${APP_NAME}-${ENVIRONMENT}-vpc"

echo "============================================"
echo "   CLOUDFORMATION STACK OPERATIONS"
echo "   Author: Asim Raza - Day 61"
echo "============================================"

echo ""
echo "[ VALIDATE TEMPLATE FIRST ]"
echo ""
echo "  Always validate before deploying!"
echo ""
echo "  aws cloudformation validate-template \\"
echo "    --template-body file://templates/02-production-vpc.yaml"
echo ""

echo "aws cloudformation validate-template \\"
echo "    --template-body \\"
echo "        file://templates/02-production-vpc.yaml \\"
echo "    --region $REGION"

echo "  ✅ Validation command printed only (NOT executed)"

echo ""
echo "[ CREATE STACK ]"
echo ""
echo "  # Create with parameters:"
echo "  aws cloudformation create-stack \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --template-body file://templates/02-production-vpc.yaml \\"
echo "    --parameters \\"
echo "      ParameterKey=AppName,ParameterValue=$APP_NAME \\"
echo "      ParameterKey=Environment,ParameterValue=$ENVIRONMENT \\"
echo "      ParameterKey=VpcCidr,ParameterValue=10.0.0.0/16 \\"
echo "    --capabilities CAPABILITY_IAM \\"
echo "    --tags \\"
echo "      Key=Project,Value=devops-journey \\"
echo "      Key=Day,Value=61 \\"
echo "    --region $REGION"
echo ""
echo "  --capabilities CAPABILITY_IAM:"
echo "  Required when template creates IAM resources"
echo "  You explicitly acknowledge it will create IAM"
echo "  --capabilities CAPABILITY_NAMED_IAM: when naming IAM resources"
echo "  --capabilities CAPABILITY_AUTO_EXPAND: for SAM/macros"

echo ""
echo "  # Wait for creation to complete:"
echo "  aws cloudformation wait stack-create-complete \\"
echo "    --stack-name $STACK_NAME"
echo ""
echo "  # Check status:"
echo "  aws cloudformation describe-stacks \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --query 'Stacks[0].StackStatus'"

echo ""
echo "[ STACK DEPLOYMENT METHODS ]"
echo ""
echo "  Method 1: cloudformation deploy (RECOMMENDED)"
echo "  Uses change sets automatically"
echo "  Creates OR updates (idempotent)"
echo ""
echo "  aws cloudformation deploy \\"
echo "    --template-file templates/02-production-vpc.yaml \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --parameter-overrides \\"
echo "      AppName=$APP_NAME \\"
echo "      Environment=$ENVIRONMENT \\"
echo "    --capabilities CAPABILITY_IAM \\"
echo "    --no-fail-on-empty-changeset \\"
echo "    --region $REGION"
echo ""
echo "  Method 2: create/update separately (older approach)"
echo "  Must know if stack exists first"
echo "  Less idiomatic, more error-prone"

# Print deployment command only — DO NOT EXECUTE
echo ""
echo "  Attempting deploy... (PRINT ONLY)"

echo "aws cloudformation deploy \\"
echo "    --template-file templates/02-production-vpc.yaml \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --parameter-overrides \\"
echo "        AppName=$APP_NAME \\"
echo "        Environment=$ENVIRONMENT \\"
echo "    --capabilities CAPABILITY_IAM \\"
echo "    --no-fail-on-empty-changeset \\"
echo "    --tags Project=devops-journey Day=61 \\"
echo "    --region $REGION"

echo "  ✅ Deployment command printed only (NOT executed)"

echo ""
echo "[ CHANGE SETS - Preview Before Apply ]"
echo ""
echo "  Change Set = 'what WILL change if I apply this?'"
echo "  Like: terraform plan"
echo "  ALWAYS use for production updates!"
echo ""
echo "  # Create change set:"
echo "  aws cloudformation create-change-set \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --change-set-name my-changes-$(date +%Y%m%d) \\"
echo "    --template-body file://templates/02-production-vpc.yaml \\"
echo "    --parameters \\"
echo "      ParameterKey=AppName,ParameterValue=$APP_NAME \\"
echo "    --capabilities CAPABILITY_IAM"
echo ""
echo "  # Describe change set (see what will change):"
echo "  aws cloudformation describe-change-set \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --change-set-name my-changes-$(date +%Y%m%d)"
echo ""
echo "  # Apply change set (after reviewing):"
echo "  aws cloudformation execute-change-set \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --change-set-name my-changes-$(date +%Y%m%d)"
echo ""
echo "  # Delete if you don't want to apply:"
echo "  aws cloudformation delete-change-set \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --change-set-name my-changes-$(date +%Y%m%d)"

echo ""
echo "[ CHANGE TYPES IN CHANGE SETS ]"
echo ""
echo "  Add:    new resource being created"
echo "  Modify: existing resource being changed"
echo "  Remove: resource being deleted"
echo ""
echo "  For Modify, 'Replacement' field shows:"
echo "  True:         resource will be DELETED and RECREATED"
echo "                → downtime! → data loss risk!"
echo "  False:        resource updated in-place (safe)"
echo "  Conditional:  depends on property change"
echo ""
echo "  ⚠️  Replacement=True on RDS = data loss!"
echo "  ALWAYS check Replacement before applying"

echo ""
echo "[ DRIFT DETECTION ]"
echo ""
echo "  Drift: someone changed infra via console"
echo "  (not through CloudFormation!)"
echo ""
echo "  # Detect drift:"
echo "  aws cloudformation detect-stack-drift \\"
echo "    --stack-name $STACK_NAME"
echo ""
echo "  # Get drift results:"
echo "  aws cloudformation describe-stack-resource-drifts \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --stack-resource-drift-status-filters MODIFIED DELETED"
echo ""
echo "  Drift status:"
echo "  IN_SYNC:     matches template"
echo "  MODIFIED:    different from template"
echo "  DELETED:     resource was deleted externally"
echo "  NOT_CHECKED: drift not yet detected"

echo ""
echo "[ STACK STATUS VALUES ]"
echo ""
echo "  CREATE_IN_PROGRESS    → creating"
echo "  CREATE_COMPLETE       → success ✅"
echo "  CREATE_FAILED         → failed, check Events"
echo "  ROLLBACK_IN_PROGRESS  → reverting..."
echo "  ROLLBACK_COMPLETE     → reverted (stack exists but empty)"
echo "  UPDATE_IN_PROGRESS    → updating"
echo "  UPDATE_COMPLETE       → updated ✅"
echo "  UPDATE_ROLLBACK_*     → update failed, reverting"
echo "  DELETE_IN_PROGRESS    → deleting"
echo "  DELETE_COMPLETE       → deleted"
echo "  DELETE_FAILED         → deletion failed (check resources)"

echo ""
echo "[ GET OUTPUTS ]"
echo ""
echo "  # Get all outputs:"
echo "  aws cloudformation describe-stacks \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --query 'Stacks[0].Outputs'"
echo ""
echo "  # Get specific output:"
echo "  aws cloudformation describe-stacks \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --query 'Stacks[0].Outputs[?OutputKey==\`VpcId\`].OutputValue' \\"
echo "    --output text"

echo ""
echo "[ DELETE STACK ]"
echo ""
echo "  aws cloudformation delete-stack \\"
echo "    --stack-name $STACK_NAME \\"
echo "    --region $REGION"
echo ""
echo "  # Wait for deletion:"
echo "  aws cloudformation wait stack-delete-complete \\"
echo "    --stack-name $STACK_NAME"
echo ""
echo "  ⚠️  DeletionPolicy: Retain resources won't be deleted"
echo "  Must delete them manually afterward"

echo ""
echo "============================================"
echo "   STACK OPERATIONS COMPLETE"
echo "============================================"
