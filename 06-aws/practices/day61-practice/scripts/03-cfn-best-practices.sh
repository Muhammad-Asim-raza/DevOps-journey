echo "============================================"
echo "   CLOUDFORMATION BEST PRACTICES"
echo "============================================"

echo ""
echo "[ 1. ALWAYS VALIDATE BEFORE DEPLOY ]"
echo ""
echo "  aws cloudformation validate-template \\"
echo "    --template-body file://template.yaml"
echo ""
echo "  Catches: YAML syntax errors, invalid references"
echo "  Does NOT catch: wrong values, permission issues"

echo ""
echo "[ 2. USE CHANGE SETS FOR UPDATES ]"
echo ""
echo "  # Never do this in production:"
echo "  aws cloudformation update-stack ...  ← blind update"
echo ""
echo "  # Always do this:"
echo "  1. Create change set"
echo "  2. Review changes (especially Replacement=True!)"
echo "  3. Apply if safe"
echo ""
echo "  Replacement=True = resource DELETED and RECREATED"
echo "  RDS: data loss! EC2: new instance (new IP)!"

echo ""
echo "[ 3. USE PARAMETERS FOR ENVIRONMENT DIFFERENCES ]"
echo ""
echo "  One template → multiple environments"
echo "  dev: t3.micro, single-AZ, no deletion protection"
echo "  prod: m5.large, multi-AZ, deletion protection"
echo ""
echo "  Parameters:"
echo "    Environment: dev | staging | production"
echo "  Conditions:"
echo "    IsProduction: !Equals [!Ref Environment, production]"
echo "  Usage:"
echo "    MultiAZ: !If [IsProduction, true, false]"

echo ""
echo "[ 4. ALWAYS TAG RESOURCES ]"
echo ""
echo "  Tags on every resource:"
echo "    Name, Environment, Project, ManagedBy"
echo ""
echo "  Use AWS::CloudFormation::Stack tags"
echo "  to propagate to all resources automatically"
echo ""
echo "  aws cloudformation create-stack \\"
echo "    --tags Key=Project,Value=app \\"
echo "           Key=ManagedBy,Value=CloudFormation"

echo ""
echo "[ 5. ENABLE TERMINATION PROTECTION ]"
echo ""
echo "  Prevents accidental stack deletion!"
echo ""
echo "  aws cloudformation update-termination-protection \\"
echo "    --enable-termination-protection \\"
echo "    --stack-name PRODUCTION-STACK"
echo ""
echo "  To delete: must disable first"
echo "  Extra friction = prevents accidents"

echo ""
echo "[ 6. STORE TEMPLATES IN S3 ]"
echo ""
echo "  Large templates (>51,200 bytes): must use S3"
echo "  Best practice: always use S3"
echo ""
echo "  # Upload template:"
echo "  aws s3 cp templates/ s3://my-cfn-templates/ --recursive"
echo ""
echo "  # Deploy from S3:"
echo "  aws cloudformation create-stack \\"
echo "    --template-url https://s3.amazonaws.com/my-cfn-templates/vpc.yaml"
echo ""
echo "  # Package (upload nested stack templates):"
echo "  aws cloudformation package \\"
echo "    --template-file root-stack.yaml \\"
echo "    --s3-bucket my-cfn-templates \\"
echo "    --output-template-file packaged-template.yaml"

echo ""
echo "[ 7. DELETION POLICY FOR STATEFUL RESOURCES ]"
echo ""
echo "  DeletionPolicy: Snapshot  ← ALWAYS for RDS, EBS"
echo "  DeletionPolicy: Retain    ← for S3 buckets with data"
echo "  DeletionPolicy: Delete    ← for stateless resources"
echo ""
echo "  # Example:"
echo "  Database:"
echo "    Type: AWS::RDS::DBInstance"
echo "    DeletionPolicy: Snapshot"
echo "    # Delete stack → take snapshot → then delete RDS"

echo ""
echo "[ 8. USE SSM PARAMETER STORE FOR CROSS-STACK CONFIG ]"
echo ""
echo "  # Instead of just !ImportValue:"
echo "  # SSM is better for configs that change often"
echo ""
echo "  # Template A: store in SSM"
echo "  SSMParameter:"
echo "    Type: AWS::SSM::Parameter"
echo "    Properties:"
echo "      Name: /\${AppName}/\${Environment}/VpcId"
echo "      Type: String"
echo "      Value: !Ref VPC"
echo ""
echo "  # Template B: read from SSM"
echo "  VpcId:"
echo "    Type: AWS::SSM::Parameter::Value<String>"
echo "    Default: /devops-journey/production/VpcId"

echo ""
echo "[ 9. USE CFNLINT FOR LINTING ]"
echo ""
echo "  pip install cfn-lint"
echo "  cfn-lint templates/02-production-vpc.yaml"
echo ""
echo "  Catches: more errors than validate-template"
echo "  Checks: best practices, deprecated properties"
echo "  Integrate: pre-commit hooks, CI/CD pipeline"

echo ""
echo "[ 10. ROLLBACK CONFIGURATION ]"
echo ""
echo "  Default: roll back entire stack on any failure"
echo "  For debugging: disable rollback to see what failed"
echo ""
echo "  # Disable rollback (debugging only!):"
echo "  aws cloudformation create-stack \\"
echo "    --on-failure DO_NOTHING \\"
echo "    ..."
echo ""
echo "  # Normal (always use in production):"
echo "  aws cloudformation create-stack \\"
echo "    --on-failure ROLLBACK \\"
echo "    ..."

echo ""
echo "============================================"
echo "   BEST PRACTICES COMPLETE"
echo "============================================"
