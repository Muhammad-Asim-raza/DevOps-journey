#!/bin/bash
# ================================================
# 01-intrinsic-functions.sh
# CloudFormation Intrinsic Functions Reference
# Author: Asim Raza - Day 61
# ================================================

echo "============================================"
echo "   CLOUDFORMATION INTRINSIC FUNCTIONS"
echo "   The building blocks of dynamic templates"
echo "============================================"

echo ""
echo "[ !Ref ]"
echo "  Returns the VALUE of a parameter or"
echo "  the PHYSICAL ID of a resource"
echo ""
echo "  # Parameter reference:"
echo "  !Ref Environment     → 'production' (string value)"
echo "  !Ref VpcCidr         → '10.0.0.0/16'"
echo ""
echo "  # Resource reference:"
echo "  !Ref MyVPC           → 'vpc-abc12345' (physical ID)"
echo "  !Ref MySecurityGroup → 'sg-xyz98765'"
echo ""
echo "  # Pseudo-parameter reference:"
echo "  !Ref AWS::Region      → 'us-east-1'"
echo "  !Ref AWS::AccountId   → '123456789012'"
echo "  !Ref AWS::StackName   → 'devops-journey-prod'"
echo "  !Ref AWS::NoValue     → removes property"

echo ""
echo "[ !Sub ]"
echo "  String substitution (like bash \${VAR})"
echo ""
echo "  # Simple substitution:"
echo "  !Sub '\${AppName}-\${Environment}-vpc'"
echo "  → 'devops-journey-staging-vpc'"
echo ""
echo "  # With AWS pseudo-parameters:"
echo "  !Sub 'arn:aws:s3:::\${AWS::AccountId}-\${AppName}'"
echo "  → 'arn:aws:s3:::123456789012-devops-journey'"
echo ""
echo "  # Multi-line with Fn::Sub:"
echo "  Fn::Sub: |"
echo "    #!/bin/bash"
echo "    echo 'Region: \${AWS::Region}'"
echo "    echo 'Stack: \${AWS::StackName}'"
echo "    echo 'App: \${AppName}'"

echo ""
echo "[ !GetAtt ]"
echo "  Get an ATTRIBUTE of a created resource"
echo "  (different from Ref which gives physical ID)"
echo ""
echo "  # EC2 attributes:"
echo "  !GetAtt MyEC2.PublicIp         → '54.123.45.67'"
echo "  !GetAtt MyEC2.PrivateIp        → '10.0.1.42'"
echo "  !GetAtt MyEC2.AvailabilityZone → 'us-east-1a'"
echo ""
echo "  # Load Balancer attributes:"
echo "  !GetAtt MyALB.DNSName          → 'my-alb-xxx.us-east-1.elb.amazonaws.com'"
echo ""
echo "  # RDS attributes:"
echo "  !GetAtt MyDB.Endpoint.Address  → 'mydb.xxx.us-east-1.rds.amazonaws.com'"
echo "  !GetAtt MyDB.Endpoint.Port     → '5432'"
echo ""
echo "  # Security Group:"
echo "  !GetAtt MySG.GroupId           → 'sg-abc12345'"
echo ""
echo "  # IAM Role:"
echo "  !GetAtt MyRole.Arn             → 'arn:aws:iam::...'"

echo ""
echo "[ !FindInMap ]"
echo "  Look up a value in Mappings section"
echo ""
echo "  # Template Mappings:"
echo "  Mappings:"
echo "    EnvironmentSizes:"
echo "      production:"
echo "        InstanceType: m5.large"
echo "      staging:"
echo "        InstanceType: t3.medium"
echo ""
echo "  # Usage:"
echo "  !FindInMap [EnvironmentSizes, !Ref Environment, InstanceType]"
echo "  With Environment=staging → 't3.medium'"

echo ""
echo "[ !If ]"
echo "  Conditional value"
echo ""
echo "  # Syntax: !If [ConditionName, IfTrue, IfFalse]"
echo ""
echo "  MultiAZ: !If [IsProduction, true, false]"
echo "  # Production: MultiAZ=true"
echo "  # Other: MultiAZ=false"
echo ""
echo "  BackupRetentionPeriod: !If [IsProduction, 7, 1]"
echo ""
echo "  DeletionPolicy: !If [IsProduction, Retain, Delete]"

echo ""
echo "[ !Select ]"
echo "  Pick item from a list by index"
echo ""
echo "  # Pick first AZ:"
echo "  !Select [0, !GetAZs '']"
echo "  → 'us-east-1a'"
echo ""
echo "  # Pick second AZ:"
echo "  !Select [1, !GetAZs '']"
echo "  → 'us-east-1b'"
echo ""
echo "  # Pick from hardcoded list:"
echo "  !Select [1, [a, b, c]]"
echo "  → 'b'"

echo ""
echo "[ !GetAZs ]"
echo "  Get list of AZs in a region"
echo ""
echo "  !GetAZs ''      → AZs in current region"
echo "  !GetAZs us-east-1 → ['us-east-1a','us-east-1b',...]"
echo ""
echo "  # Combined with !Select:"
echo "  AvailabilityZone: !Select [0, !GetAZs '']"

echo ""
echo "[ !Join ]"
echo "  Join list of strings"
echo ""
echo "  !Join [',', [value1, value2, value3]]"
echo "  → 'value1,value2,value3'"
echo ""
echo "  # Join ARNs:"
echo "  !Join"
echo "    - ','"
echo "    - - !Ref Subnet1"
echo "      - !Ref Subnet2"
echo "      - !Ref Subnet3"

echo ""
echo "[ !Split ]"
echo "  Split string into list"
echo ""
echo "  !Split [',', 'a,b,c']"
echo "  → [a, b, c]"

echo ""
echo "[ !ImportValue ]"
echo "  Import exported value from ANOTHER stack"
echo ""
echo "  # Stack A exports:"
echo "  Outputs:"
echo "    VpcId:"
echo "      Export:"
echo "        Name: MyApp-VpcId"
echo "      Value: !Ref MyVPC"
echo ""
echo "  # Stack B imports:"
echo "  VpcId: !ImportValue MyApp-VpcId"
echo ""
echo "  This is cross-stack referencing!"
echo "  Change VPC in Stack A → Stack B auto-references new value"

echo ""
echo "[ !Base64 ]"
echo "  Encode string to Base64"
echo "  Required for EC2 UserData"
echo ""
echo "  UserData:"
echo "    !Base64 |"
echo "      #!/bin/bash"
echo "      yum update -y"
echo ""
echo "  # With Fn::Sub for variable substitution:"
echo "  UserData:"
echo "    Fn::Base64:"
echo "      !Sub |"
echo "        #!/bin/bash"
echo "        echo \${Environment} > /tmp/env.txt"

echo ""
echo "[ !Cidr ]"
echo "  Generate CIDR blocks from parent CIDR"
echo ""
echo "  !Cidr [!Ref VpcCidr, 6, 8]"
echo "  # VpcCidr=10.0.0.0/16, 6 subnets, /24 each"
echo "  → [10.0.0.0/24, 10.0.1.0/24, ...]"
echo ""
echo "  Combined:"
echo "  !Select [0, !Cidr [!Ref VpcCidr, 6, 8]]"
echo "  → First /24 subnet"

echo ""
echo "[ YAML SHORTHAND vs FULL SYNTAX ]"
echo "  # Both are identical:"
echo "  !Ref MyVPC           = Ref: MyVPC"
echo "  !Sub 'hello \${Name}' = Fn::Sub: 'hello \${Name}'"
echo "  !GetAtt R.Attr       = Fn::GetAtt: [R, Attr]"
echo "  !If [C, T, F]        = Fn::If: [C, T, F]"
echo "  !FindInMap [M, K, V] = Fn::FindInMap: [M, K, V]"
echo "  # Use YAML shorthand (!X) for cleaner templates"

echo ""
echo "============================================"
echo "   INTRINSIC FUNCTIONS COMPLETE"
echo "============================================"
