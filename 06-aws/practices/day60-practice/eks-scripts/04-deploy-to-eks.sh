#!/bin/bash
# ================================================
# 04-deploy-to-eks.sh
# Deploy Day 49/52 manifests to EKS
# Author: Asim Raza - Day 60
# ================================================

REGION="${AWS_DEFAULT_REGION:-us-east-1}"
CLUSTER_NAME="devops-journey"

echo "============================================"
echo "   DEPLOY TO EKS"
echo "   Connecting Day 49 (ArgoCD) + Day 52 (CI/CD)"
echo "   to Day 60 (EKS)"
echo "   Author: Asim Raza - Day 60"
echo "============================================"

echo ""
echo "[ INSTALL AWS LOAD BALANCER CONTROLLER ]"
echo ""
echo "  Required to use ALB with EKS"
echo "  Uses IRSA for permissions (no static keys)"
echo ""
echo "  # Install via Helm:"
echo "  helm repo add eks https://aws.github.io/eks-charts"
echo "  helm repo update"
echo ""
echo "  helm install aws-load-balancer-controller \\"
echo "    eks/aws-load-balancer-controller \\"
echo "    -n kube-system \\"
echo "    --set clusterName=$CLUSTER_NAME \\"
echo "    --set serviceAccount.create=false \\"
echo "    --set serviceAccount.name=aws-load-balancer-controller"
echo ""
echo "  # Verify installation:"
echo "  kubectl get deployment -n kube-system \\"
echo "    aws-load-balancer-controller"

echo ""
echo "[ INSTALL METRICS SERVER ]"
echo ""
echo "  Required for HPA (Horizontal Pod Autoscaler)"
echo "  kubectl apply -f \\"
echo "    https://github.com/kubernetes-sigs/metrics-server/releases/latest/download/components.yaml"
echo ""
echo "  kubectl top nodes"
echo "  kubectl top pods -n production"

echo ""
echo "[ DEPLOY MANIFESTS ]"
echo ""
echo "  # Apply in order:"
echo ""
echo "  1. Namespaces first:"
echo "  kubectl apply -f k8s-manifests/namespace.yaml"
echo ""
echo "  2. Service Account (IRSA link):"
echo "  kubectl apply -f k8s-manifests/service-account.yaml"
echo ""
echo "  3. Deploy application:"
echo "  kubectl apply -f k8s-manifests/deployment-eks.yaml"
echo ""
echo "  4. Service and Ingress (creates ALB):"
echo "  kubectl apply -f k8s-manifests/service-ingress.yaml"
echo ""
echo "  # Check everything:"
echo "  kubectl get all -n production"

if command -v kubectl &>/dev/null; then
    echo ""
    echo "[ APPLYING MANIFESTS (demo) ]"

    # Apply if cluster is available
    kubectl apply -f k8s-manifests/namespace.yaml \
        2>/dev/null || \
        echo "  (Apply when cluster is running)"

    kubectl get namespaces 2>/dev/null | \
        grep -E "production|staging" || \
        echo "  Namespaces: staging, production"
fi

echo ""
echo "[ USEFUL kubectl COMMANDS FOR EKS ]"
echo ""
echo "  # Watch pods start:"
echo "  kubectl get pods -n production -w"
echo ""
echo "  # See pod details (events, errors):"
echo "  kubectl describe pod POD_NAME -n production"
echo ""
echo "  # Check pod logs:"
echo "  kubectl logs -f POD_NAME -n production"
echo "  kubectl logs -f -l app=devops-platform -n production"
echo ""
echo "  # Execute in pod:"
echo "  kubectl exec -it POD_NAME -n production -- /bin/sh"
echo ""
echo "  # Check ALB creation:"
echo "  kubectl describe ingress devops-platform-ingress \\"
echo "    -n production"
echo ""
echo "  # Port-forward for local testing:"
echo "  kubectl port-forward svc/devops-platform-svc 8000:80 \\"
echo "    -n production"
echo ""
echo "  # Check HPA:"
echo "  kubectl get hpa -n production"
echo "  kubectl describe hpa devops-platform-hpa -n production"

echo ""
echo "[ GITOPS WITH ARGOCD ON EKS ]"
echo ""
echo "  Install ArgoCD on EKS:"
echo "  kubectl create namespace argocd"
echo "  kubectl apply -n argocd -f \\"
echo "    https://raw.githubusercontent.com/argoproj/argo-cd/stable/manifests/install.yaml"
echo ""
echo "  # Access ArgoCD UI:"
echo "  kubectl port-forward svc/argocd-server -n argocd 8080:443"
echo ""
echo "  # Apply Day 49 ArgoCD Application:"
echo "  kubectl apply -f \\"
echo "    ~/DevOps-journey/05-cicd/practices/day49-practice/gitops-repo/argocd/applications/"
echo ""
echo "  Day 49 → Day 60 connection:"
echo "  ArgoCD watches your Git manifests"
echo "  Auto-deploys to this EKS cluster"
echo "  FULL GitOps on production EKS!"

echo ""
echo "[ CLUSTER AUTOSCALER ]"
echo ""
echo "  Scale NODES when pods cannot be scheduled"
echo "  (HPA scales pods, CA scales nodes)"
echo ""
echo "  Install:"
echo "  kubectl apply -f https://raw.githubusercontent.com/kubernetes/autoscaler/master/cluster-autoscaler/cloudprovider/aws/examples/cluster-autoscaler-autodiscover.yaml"
echo ""
echo "  Configure:"
echo "  kubectl -n kube-system annotate deployment.apps/cluster-autoscaler \\"
echo "    cluster-autoscaler.kubernetes.io/safe-to-evict='false'"
echo ""
echo "  Workflow:"
echo "  Pod cannot schedule (insufficient resources)"
echo "  → CA detects unschedulable pod"
echo "  → CA checks node group min/max"
echo "  → CA adds EC2 node (5-10 minutes)"
echo "  → Pod schedules on new node"
echo ""
echo "  HPA + CA together = full auto-scaling:"
echo "  Traffic spike → HPA adds pods"
echo "  Pods can't fit → CA adds nodes"
echo "  Traffic drops → HPA removes pods"
echo "  Nodes underutilized → CA removes nodes"

echo ""
echo "[ ⚠️  CLEANUP - IMPORTANT! ]"
echo ""
echo "  EKS is expensive! Delete when done:"
echo ""
echo "  # Delete Kubernetes resources first:"
echo "  kubectl delete all --all -n production"
echo "  kubectl delete all --all -n staging"
echo ""
echo "  # Delete cluster (this removes everything):"
echo "  eksctl delete cluster --name $CLUSTER_NAME"
echo ""
echo "  # Verify deletion:"
echo "  aws eks list-clusters --region $REGION"
echo "  aws ec2 describe-vpcs --filter Name=tag:alpha.eksctl.io/cluster-name,Values=$CLUSTER_NAME"

echo ""
echo "============================================"
echo "   EKS DEPLOYMENT GUIDE COMPLETE"
echo "============================================"
