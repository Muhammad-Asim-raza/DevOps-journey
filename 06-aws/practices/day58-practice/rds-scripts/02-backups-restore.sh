#!/bin/bash
# ================================================
# 02-backups-restore.sh
# RDS Backups, Snapshots, and Point-in-Time Restore
# Author: Asim Raza - Day 58
# ================================================

echo "source ../rds-configs/rds-config.sh 2>/dev/null || {"
    DB_IDENTIFIER="devops-journey-postgres"
    REGION="us-east-1"
echo "}"

echo "============================================"
echo "   RDS BACKUPS AND RESTORE"
echo "   Author: Asim Raza - Day 58"
echo "============================================"

echo ""
echo "[ TWO TYPES OF BACKUPS ]"
echo ""
echo "  1. AUTOMATED BACKUPS (continuous):"
echo "     - Daily full backup during backup window"
echo "     - Transaction logs every 5 minutes"
echo "     - Enables: point-in-time restore"
echo "     - Retention: 1-35 days (you choose)"
echo "     - Stored in S3 (free storage = DB size)"
echo "     - Auto-deleted when retention expires"
echo "     - Enabled by default (backup-retention-period > 0)"
echo ""
echo "  2. MANUAL SNAPSHOTS:"
echo "     - You trigger them explicitly"
echo "     - Kept FOREVER (until you delete)"
echo "     - Good for: before major changes"
echo "     - Copy to other regions (cross-region DR)"
echo "     - Share with other AWS accounts"
echo "     - Charged: $0.095/GB/month beyond free tier"

echo ""
echo "[ AUTOMATED BACKUP SETTINGS ]"
echo ""
echo "  # Set backup retention to 7 days:"
echo "  aws rds modify-db-instance \\"
echo "    --db-instance-identifier $DB_IDENTIFIER \\"
echo "    --backup-retention-period 7 \\"
echo "    --preferred-backup-window '03:00-04:00' \\"
echo "    --apply-immediately"
echo ""
echo "  Backup window: choose low-traffic time"
echo "  03:00-04:00 UTC = common choice"
echo "  Brief performance impact during backup"
echo "  Multi-AZ: backup taken from standby (no impact!)"

echo ""
echo "[ MANUAL SNAPSHOT OPERATIONS ]"
echo ""
echo "  # Take manual snapshot:"
echo "aws rds create-db-snapshot \\"
echo "    --db-instance-identifier \"$DB_IDENTIFIER\" \\"
echo "    --db-snapshot-identifier \"${DB_IDENTIFIER}-snap-day58\" \\"
echo "    --tags Key=Purpose,Value=day58-demo \\"
echo "    --region \"$REGION\" 2>/dev/null && \\"
    echo "  ✅ Snapshot started: ${DB_IDENTIFIER}-snap-day58" || \
    echo "  aws rds create-db-snapshot \\"
    echo "    --db-instance-identifier $DB_IDENTIFIER \\"
    echo "    --db-snapshot-identifier ${DB_IDENTIFIER}-snap-day58"

echo ""
echo "  # List snapshots for an instance:"
echo "  aws rds describe-db-snapshots \\"
echo "    --db-instance-identifier $DB_IDENTIFIER \\"
echo "    --output table"

echo "aws rds describe-db-snapshots \\"
echo "    --db-instance-identifier \"$DB_IDENTIFIER\" \\"
echo "    --query 'DBSnapshots[*].[DBSnapshotIdentifier,Status,SnapshotCreateTime,AllocatedStorage]' \\"
echo "    --output table \\"
echo "    --region \"$REGION\" 2>/dev/null || \\"
    echo "  (no snapshots or credentials not configured)"

echo ""
echo "  # Copy snapshot to another region (DR!):"
echo "  aws rds copy-db-snapshot \\"
echo "    --source-db-snapshot-identifier \\"
echo "      arn:aws:rds:us-east-1:123456789012:snapshot:${DB_IDENTIFIER}-snap \\"
echo "    --target-db-snapshot-identifier ${DB_IDENTIFIER}-snap-eu \\"
echo "    --source-region us-east-1 \\"
echo "    --region eu-west-1 \\"
echo "    --copy-tags"
echo ""
echo "  # Share snapshot with another AWS account:"
echo "  aws rds modify-db-snapshot-attribute \\"
echo "    --db-snapshot-identifier ${DB_IDENTIFIER}-snap \\"
echo "    --attribute-name restore \\"
echo "    --values-to-add PARTNER-ACCOUNT-ID"

echo ""
echo "[ POINT-IN-TIME RESTORE ]"
echo ""
echo "  The most powerful RDS recovery feature!"
echo "  Restore to any second within retention period"
echo ""
echo "  Scenario:"
echo "  9:00am: developer runs 'DROP TABLE users;'"
echo "  9:05am: alert fires (users table missing!)"
echo "  9:06am: restore to 8:59:59am"
echo "  9:15am: data fully restored"
echo ""
echo "  # Restore to specific time:"
echo "  aws rds restore-db-instance-to-point-in-time \\"
echo "    --source-db-instance-identifier $DB_IDENTIFIER \\"
echo "    --target-db-instance-identifier ${DB_IDENTIFIER}-restored \\"
echo "    --restore-time 2024-08-14T08:59:59Z \\"
echo "    --db-instance-class db.t3.micro \\"
echo "    --db-subnet-group-name devops-journey-db-subnet-group \\"
echo "    --vpc-security-group-ids sg-xxx \\"
echo "    --no-publicly-accessible"
echo ""
echo "  IMPORTANT: restores to a NEW instance"
echo "  Does NOT overwrite existing database"
echo "  After restore: verify data, then update"
echo "  app connection string to new endpoint"
echo ""
echo "  # Restore from manual snapshot:"
echo "  aws rds restore-db-instance-from-db-snapshot \\"
echo "    --db-instance-identifier ${DB_IDENTIFIER}-from-snap \\"
echo "    --db-snapshot-identifier ${DB_IDENTIFIER}-snap \\"
echo "    --db-instance-class db.t3.micro \\"
echo "    --db-subnet-group-name devops-journey-db-subnet-group"

echo ""
echo "[ BACKUP BEST PRACTICES ]"
echo ""
echo "  ✅ Retention: minimum 7 days (14-35 for compliance)"
echo "  ✅ Manual snapshot: before every major deployment"
echo "  ✅ Copy snapshots: cross-region for DR"
echo "  ✅ Test restores: quarterly restore drills"
echo "     (If you never test, backups are useless!)"
echo "  ✅ Multi-AZ: backups from standby (no performance hit)"
echo "  ✅ Deletion protection: prevent accidental delete"
echo "  ✅ Enable enhanced monitoring: OS-level metrics"

echo ""
echo "  BACKUP BEFORE:"
echo "  - Engine version upgrades"
echo "  - Major schema changes"
echo "  - Parameter group changes"
echo "  - Instance class changes"
echo "  - Storage modifications"

echo ""
echo "============================================"
echo "   BACKUPS AND RESTORE COMPLETE"
echo "============================================"
