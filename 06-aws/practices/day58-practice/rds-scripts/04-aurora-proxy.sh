echo "============================================"
echo "   AMAZON AURORA AND RDS PROXY"
echo "   AWS-native database + connection pooling"
echo "============================================"

echo ""
echo "[ WHAT IS AURORA? ]"
echo ""
echo "  Aurora = AWS re-engineered relational database"
echo "  Compatible with: MySQL 5.7/8.0 and PostgreSQL 13-16"
echo "  Drop-in replacement: same SQL, drivers, tools"
echo ""
echo "  HOW IT'S DIFFERENT from RDS MySQL/PostgreSQL:"
echo ""
echo "  RDS MySQL:"
echo "  ┌─────────────────────────────────────┐"
echo "  │ Instance (compute + OS)             │"
echo "  │ ┌──────────────────────────────┐   │"
echo "  │ │ MySQL engine                 │   │"
echo "  │ └──────────────────────────────┘   │"
echo "  │ ┌──────────────────────────────┐   │"
echo "  │ │ EBS Volume (data storage)    │   │"
echo "  │ └──────────────────────────────┘   │"
echo "  └─────────────────────────────────────┘"
echo "  Storage: single EBS, replicated to standby"
echo ""
echo "  Aurora:"
echo "  ┌───────────────────────────────────────────────┐"
echo "  │ Writer Instance    Reader Instances (up to 15)│"
echo "  │ (compute only)     (compute only)             │"
echo "  └──────────┬─────────────────────┬─────────────┘"
echo "             │                     │"
echo "             ▼                     ▼"
echo "  ┌───────────────────────────────────────────────┐"
echo "  │ Aurora Storage (separate, distributed)        │"
echo "  │ 6 copies across 3 AZs (2 per AZ)            │"
echo "  │ Auto-grows in 10GB increments (up to 128TB)  │"
echo "  │ Repairs itself from corruption automatically  │"
echo "  └───────────────────────────────────────────────┘"

echo ""
echo "[ AURORA ADVANTAGES ]"
echo ""
echo "  Performance:"
echo "  5x faster than MySQL"
echo "  3x faster than PostgreSQL"
echo "  Reason: custom storage, no binlog overhead"
echo ""
echo "  Storage:"
echo "  Shared storage layer (writer + all readers share)"
echo "  6 copies across 3 AZs (automatic)"
echo "  Auto-scales: 10GB → 128TB"
echo "  No storage provisioning needed"
echo ""
echo "  Availability:"
echo "  Writer failover: < 30 seconds"
echo "  (faster than RDS Multi-AZ ~60 seconds)"
echo "  Can lose 2 of 6 storage copies: reads still work"
echo "  Can lose 3 of 6 storage copies: writes stop"
echo ""
echo "  Readers:"
echo "  Up to 15 read replicas (RDS MySQL: 5)"
echo "  Same shared storage → zero replica lag!"
echo "  No data to copy to replicas"
echo "  Cluster reader endpoint load-balances automatically"
echo ""
echo "  Aurora Serverless v2:"
echo "  Scales compute up/down automatically"
echo "  Minimum: 0.5 ACU (Aurora Capacity Units)"
echo "  Maximum: you set (e.g., 128 ACU)"
echo "  Perfect for: unpredictable traffic, dev/test"

echo ""
echo "[ AURORA CLUSTER ENDPOINTS ]"
echo ""
echo "  Cluster endpoints (use these, not instance):"
echo ""
echo "  Writer (cluster endpoint):"
echo "  mydb.cluster-xxx.us-east-1.rds.amazonaws.com"
echo "  → always points to current writer"
echo "  → reconnect automatically after failover"
echo ""
echo "  Reader (cluster reader endpoint):"
echo "  mydb.cluster-ro-xxx.us-east-1.rds.amazonaws.com"
echo "  → load-balances across all reader instances"
echo "  → add more readers → automatic load distribution"
echo ""
echo "  Custom endpoints:"
echo "  Point to subset of instances"
echo "  Use: large instances for heavy analytics"
echo "       small instances for lightweight queries"

echo ""
echo "[ CREATE AURORA POSTGRESQL CLUSTER ]"
echo ""
echo "  # Step 1: Create cluster parameter group"
echo "  aws rds create-db-cluster-parameter-group \\"
echo "    --db-cluster-parameter-group-name aurora-pg16-params \\"
echo "    --db-parameter-group-family aurora-postgresql16 \\"
echo "    --description 'Aurora PostgreSQL 16 params'"
echo ""
echo "  # Step 2: Create Aurora cluster"
echo "  aws rds create-db-cluster \\"
echo "    --db-cluster-identifier devops-journey-aurora \\"
echo "    --engine aurora-postgresql \\"
echo "    --engine-version 16.3 \\"
echo "    --master-username dbadmin \\"
echo "    --master-user-password '\$SECRET' \\"
echo "    --database-name devopsdb \\"
echo "    --db-subnet-group-name devops-journey-db-subnet-group \\"
echo "    --vpc-security-group-ids sg-xxx \\"
echo "    --backup-retention-period 7 \\"
echo "    --storage-encrypted \\"
echo "    --deletion-protection"
echo ""
echo "  # Step 3: Add writer instance"
echo "  aws rds create-db-instance \\"
echo "    --db-instance-identifier devops-journey-aurora-writer \\"
echo "    --db-cluster-identifier devops-journey-aurora \\"
echo "    --engine aurora-postgresql \\"
echo "    --db-instance-class db.r6g.large \\"
echo "    --availability-zone us-east-1a"
echo ""
echo "  # Step 4: Add reader instance"
echo "  aws rds create-db-instance \\"
echo "    --db-instance-identifier devops-journey-aurora-reader-1 \\"
echo "    --db-cluster-identifier devops-journey-aurora \\"
echo "    --engine aurora-postgresql \\"
echo "    --db-instance-class db.r6g.large \\"
echo "    --availability-zone us-east-1b"

echo ""
echo "[ RDS PROXY ]"
echo ""
echo "  PROBLEM: Database connection limits"
echo ""
echo "  RDS PostgreSQL db.t3.micro: max_connections ~87"
echo "  100 Lambda functions × 1 connection each = 100"
echo "  EXCEEDS LIMIT: 'too many connections' error"
echo ""
echo "  Lambda specific problem:"
echo "  Each Lambda invocation opens DB connection"
echo "  Lambda scales to 1000 concurrent = 1000 connections"
echo "  Database falls over"
echo ""
echo "  RDS PROXY SOLUTION:"
echo ""
cat << 'DIAGRAM'
  Lambda ×1000     Lambda ×1000
  functions        functions
      │                 │
      │ 1000 connections│
      ▼                 ▼
  ┌───────────────────────────────┐
  │  RDS PROXY                    │
  │  Connection pool              │
  │  Multiplexes connections      │
  │  Reuses idle connections      │
  └───────────────────────────────┘
          │ 20-50 connections
          ▼
  ┌──────────────────┐
  │ RDS PostgreSQL   │
  │ 87 max_conn: OK! │
  └──────────────────┘
DIAGRAM

echo ""
echo "  RDS Proxy benefits:"
echo "  ✅ Connection pooling (share connections)"
echo "  ✅ Failover faster (proxy holds connections)"
echo "  ✅ IAM authentication to database"
echo "  ✅ Secrets Manager integration"
echo "  ✅ Reduces DB load (fewer open connections)"
echo ""
echo "  Create RDS Proxy:"
echo "  aws rds create-db-proxy \\"
echo "    --db-proxy-name devops-journey-proxy \\"
echo "    --engine-family POSTGRESQL \\"
echo "    --auth AuthScheme=SECRETS,\\"
echo "           SecretArn=arn:aws:secretsmanager:us-east-1:xxx:secret:rds/password,\\"
echo "           IAMAuth=REQUIRED \\"
echo "    --role-arn arn:aws:iam::xxx:role/RDSProxyRole \\"
echo "    --vpc-subnet-ids subnet-xxx subnet-yyy \\"
echo "    --vpc-security-group-ids sg-xxx \\"
echo "    --require-tls"
echo ""
echo "  Proxy endpoint (use this in Lambda/ECS):"
echo "  devops-journey-proxy.proxy-xxx.us-east-1.rds.amazonaws.com"
echo ""
echo "  Cost: $0.015/vCPU/hour of proxied DB instance"
echo "  Worth it for: Lambda, ECS, many microservices"

echo ""
echo "============================================"
echo "   AURORA AND RDS PROXY COMPLETE"
echo "============================================"
