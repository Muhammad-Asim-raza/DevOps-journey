#!/bin/bash
# ================================================
# 02-lambda-triggers.sh
# Lambda Triggers and Event Sources
# Author: Asim Raza - Day 62
# ================================================

REGION="${AWS_DEFAULT_REGION:-us-east-1}"
FUNCTION_NAME="devops-journey-hello-world"

echo "============================================"
echo "   LAMBDA TRIGGERS AND EVENT SOURCES"
echo "   How Lambda gets invoked"
echo "============================================"

echo ""
echo "[ TRIGGER TYPES ]"
echo ""
echo "  SYNCHRONOUS (caller waits for response):"
echo "  → API Gateway HTTP API"
echo "  → API Gateway REST API"
echo "  → Application Load Balancer"
echo "  → Cognito (authentication)"
echo "  → CloudFront (Lambda@Edge)"
echo "  → Direct invocation (SDK/CLI)"
echo ""
echo "  ASYNCHRONOUS (fire and forget):"
echo "  → S3 events (object created/deleted)"
echo "  → EventBridge (CloudWatch Events)"
echo "  → SNS (topic notifications)"
echo "  → CloudFormation custom resources"
echo ""
echo "  POLLING (Lambda reads from stream/queue):"
echo "  → SQS (reads messages from queue)"
echo "  → Kinesis (reads stream records)"
echo "  → DynamoDB Streams"
echo "  → Kafka (MSK)"

echo ""
echo "[ TRIGGER 1: S3 Event Notification ]"
echo ""
echo "  # Allow S3 to invoke Lambda:"
echo "  aws lambda add-permission \\"
echo "    --function-name $FUNCTION_NAME \\"
echo "    --statement-id s3-trigger \\"
echo "    --action lambda:InvokeFunction \\"
echo "    --principal s3.amazonaws.com \\"
echo "    --source-arn arn:aws:s3:::my-bucket \\"
echo "    --source-account $(aws sts get-caller-identity --query Account --output text 2>/dev/null || echo 'ACCOUNT_ID')"
echo ""
echo "  # Configure S3 to send events:"
echo "  aws s3api put-bucket-notification-configuration \\"
echo "    --bucket my-bucket \\"
echo "    --notification-configuration '{"
echo "      \"LambdaFunctionConfigurations\": [{"
echo "        \"Events\": [\"s3:ObjectCreated:*\"],"
echo "        \"LambdaFunctionArn\": \"arn:aws:lambda:REGION:ACCOUNT:function:FUNCTION\","
echo "        \"Filter\": {"
echo "          \"Key\": {"
echo "            \"FilterRules\": ["
echo "              {\"Name\": \"prefix\", \"Value\": \"uploads/\"},"
echo "              {\"Name\": \"suffix\", \"Value\": \".jpg\"}"
echo "            ]"
echo "          }"
echo "        }"
echo "      }]"
echo "    }'"

echo ""
echo "[ TRIGGER 2: SQS Queue ]"
echo ""
echo "  # Create SQS queue:"
echo "  SQS_URL=\$(aws sqs create-queue \\"
echo "    --queue-name devops-journey-queue.fifo \\"
echo "    --attributes FifoQueue=true,ContentBasedDeduplication=true \\"
echo "    --query QueueUrl --output text)"
echo ""
echo "  # Create Event Source Mapping:"
echo "  aws lambda create-event-source-mapping \\"
echo "    --function-name $FUNCTION_NAME \\"
echo "    --event-source-arn arn:aws:sqs:REGION:ACCOUNT:queue.fifo \\"
echo "    --batch-size 10 \\"
echo "    --function-response-types ReportBatchItemFailures"
echo ""
echo "  batch-size: process up to 10 messages at once"
echo "  ReportBatchItemFailures: only retry failed items"
echo "  (without it: entire batch retried if 1 fails!)"

echo ""
echo "[ TRIGGER 3: EventBridge Schedule ]"
echo ""
echo "  # Run Lambda every day at 2am UTC:"
echo "  aws events put-rule \\"
echo "    --name daily-cleanup \\"
echo "    --schedule-expression 'cron(0 2 * * ? *)' \\"
echo "    --description 'Daily cleanup task'"
echo ""
echo "  # Target the Lambda:"
echo "  aws events put-targets \\"
echo "    --rule daily-cleanup \\"
echo "    --targets Id=1,Arn=arn:aws:lambda:REGION:ACCOUNT:function:$FUNCTION_NAME"
echo ""
echo "  # Allow EventBridge to invoke Lambda:"
echo "  aws lambda add-permission \\"
echo "    --function-name $FUNCTION_NAME \\"
echo "    --statement-id eventbridge-trigger \\"
echo "    --action lambda:InvokeFunction \\"
echo "    --principal events.amazonaws.com \\"
echo "    --source-arn arn:aws:events:REGION:ACCOUNT:rule/daily-cleanup"
echo ""
echo "  Cron expression format (Lambda-specific):"
echo "  cron(minutes hours day month day-of-week year)"
echo "  cron(0 2 * * ? *)     = every day at 2am UTC"
echo "  cron(0 9 ? * MON-FRI *) = weekdays at 9am"
echo "  rate(5 minutes)        = every 5 minutes"
echo "  rate(1 day)            = every day"

echo ""
echo "[ CONCURRENCY AND SCALING ]"
echo ""
echo "  Lambda scales: 1 execution per request"
echo "  1000 simultaneous requests = 1000 Lambda instances"
echo "  Default account limit: 1000 concurrent (soft limit)"
echo "  Request increase: AWS Support"
echo ""
echo "  RESERVED CONCURRENCY:"
echo "  # Limit function to max N concurrent"
echo "  aws lambda put-function-concurrency \\"
echo "    --function-name $FUNCTION_NAME \\"
echo "    --reserved-concurrent-executions 50"
echo "  Use: protect downstream (RDS max_connections!)"
echo "  50 concurrent Lambdas = max 50 DB connections"
echo ""
echo "  PROVISIONED CONCURRENCY (keep-warm):"
echo "  aws lambda put-provisioned-concurrency-config \\"
echo "    --function-name $FUNCTION_NAME \\"
echo "    --qualifier production \\"
echo "    --provisioned-concurrent-executions 10"
echo "  Keeps 10 instances warm (no cold starts)"
echo "  Cost: $0.015/GB-hour (always billed)"
echo "  Use: latency-sensitive APIs, avoid cold starts"
echo ""
echo "  THROTTLING:"
echo "  If concurrency limit reached:"
echo "  Sync (API GW): 429 TooManyRequests error"
echo "  Async (S3/SNS): queued and retried automatically"

echo ""
echo "[ DEAD LETTER QUEUES (DLQ) ]"
echo ""
echo "  For async invocations that repeatedly fail:"
echo "  Lambda retries 2 times by default"
echo "  After 3 failures: event goes to DLQ (SQS or SNS)"
echo ""
echo "  aws lambda update-function-configuration \\"
echo "    --function-name $FUNCTION_NAME \\"
echo "    --dead-letter-config TargetArn=arn:aws:sqs:REGION:ACCOUNT:dlq"
echo ""
echo "  Monitor DLQ: receive messages for debugging"
echo "  Alert on DLQ: CloudWatch alarm on ApproximateNumberOfMessages"

echo ""
echo "[ LAMBDA DESTINATIONS (modern DLQ replacement) ]"
echo ""
echo "  aws lambda put-function-event-invoke-config \\"
echo "    --function-name $FUNCTION_NAME \\"
echo "    --maximum-retry-attempts 2 \\"
echo "    --destination-config '{"
echo "      \"OnSuccess\": {"
echo "        \"Destination\": \"arn:aws:sqs:REGION:ACCOUNT:success-queue\""
echo "      },"
echo "      \"OnFailure\": {"
echo "        \"Destination\": \"arn:aws:sqs:REGION:ACCOUNT:failure-queue\""
echo "      }"
echo "    }'"
echo ""
echo "  OnSuccess AND OnFailure destinations"
echo "  More flexible than DLQ (only failed)"
echo "  Can send to: SQS, SNS, Lambda, EventBridge"

echo ""
echo "============================================"
echo "   TRIGGERS AND CONCURRENCY COMPLETE"
echo "============================================"
