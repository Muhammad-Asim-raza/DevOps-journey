echo "[ VPC ENDPOINTS ]"
echo ""
echo "  Problem without endpoints:"
echo "  EC2 in private subnet needs S3"
echo "  Route: EC2 → NAT GW → Internet → S3"
echo "  Cost: NAT GW data transfer fees"
echo "  Security: traffic goes over internet"
echo ""
echo "  VPC Endpoint solution:"
echo "  EC2 → VPC Endpoint → S3 (private AWS network)"
echo "  Cost: no NAT GW fees for S3 traffic"
echo "  Security: traffic NEVER leaves AWS network"
echo ""
echo "  TWO TYPES:"
echo ""
echo "  Gateway Endpoint (free):"
echo "  Services: S3 and DynamoDB ONLY"
echo "  Added to route table as target"
echo "  aws ec2 create-vpc-endpoint \\"
echo "    --vpc-id vpc-xxx \\"
echo "    --service-name com.amazonaws.us-east-1.s3 \\"
echo "    --vpc-endpoint-type Gateway \\"
echo "    --route-table-ids rtb-PRIVATE"
echo ""
echo "  Interface Endpoint (costs ~\$7/month):"
echo "  Services: most other AWS services"
echo "  Creates an ENI (Elastic Network Interface)"
echo "  Uses PrivateLink technology"
echo "  Services: EC2 API, SSM, Secrets Manager, ECR..."
echo "  aws ec2 create-vpc-endpoint \\"
echo "    --vpc-id vpc-xxx \\"
echo "    --service-name com.amazonaws.us-east-1.ecr.api \\"
echo "    --vpc-endpoint-type Interface \\"
echo "    --subnet-ids subnet-PRIVATE \\"
echo "    --security-group-ids sg-xxx"

echo ""
echo "[ VPC PEERING ]"
echo ""
echo "  Connect TWO VPCs so they can communicate"
echo "  Traffic stays on AWS private network"
echo "  Works across: regions and accounts"
echo ""
echo "  Use cases:"
echo "  Shared services VPC → spoke VPCs"
echo "  Development VPC → Production VPC (read-only)"
echo "  Company A VPC → Company B VPC (partner)"
echo ""
echo "  LIMITATIONS:"
echo "  NO transitive routing!"
echo "  VPC-A peered with VPC-B"
echo "  VPC-B peered with VPC-C"
echo "  VPC-A CANNOT reach VPC-C"
echo "  (must peer A-C directly)"
echo ""
echo "  For hub-and-spoke: use Transit Gateway"
echo "  (more expensive but scales better)"
echo ""
echo "  CREATE PEERING:"
echo "  # From requesting VPC:"
echo "  aws ec2 create-vpc-peering-connection \\"
echo "    --vpc-id vpc-REQUESTER \\"
echo "    --peer-vpc-id vpc-ACCEPTER \\"
echo "    --peer-region us-west-2"
echo ""
echo "  # Accept from the other side:"
echo "  aws ec2 accept-vpc-peering-connection \\"
echo "    --vpc-peering-connection-id pcx-xxx"
echo ""
echo "  # Add routes in BOTH VPCs:"
echo "  aws ec2 create-route \\"
echo "    --route-table-id rtb-VPC-A \\"
echo "    --destination-cidr-block 10.1.0.0/16 \\"
echo "    --vpc-peering-connection-id pcx-xxx"

