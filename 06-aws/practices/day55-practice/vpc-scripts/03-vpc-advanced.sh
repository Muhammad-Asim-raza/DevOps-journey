echo "  Protocol (TCP=6, UDP=17)"
echo "  Bytes and packets"
echo "  Action: ACCEPT or REJECT"
echo "  Timestamp"
echo ""
echo "  Destination: CloudWatch Logs or S3"
echo ""
echo "  Create VPC Flow Log:"
echo "  aws ec2 create-flow-logs \\"
echo "    --resource-type VPC \\"
echo "    --resource-ids vpc-xxx \\"
echo "    --traffic-type ALL \\"
echo "    --log-destination-type cloud-watch-logs \\"
echo "    --log-group-name /aws/vpc/flowlogs \\"
echo "    --deliver-logs-permission-arn arn:aws:iam::xxx:role/FlowLogsRole"
echo ""
echo "  Use for:"
echo "  Security: who is connecting to what"
echo "  Debugging: why is traffic rejected"
